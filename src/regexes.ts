const DATE_REGEX_SOURCE = `((\\d\\d[2468][048]|\\d\\d[13579][26]|\\d\\d0[48]|[02468][048]00|[13579][26]00)-02-29|\\d{4}-((0[13578]|1[02])-(0[1-9]|[12]\\d|3[01])|(0[469]|11)-(0[1-9]|[12]\\d|30)|(02)-(0[1-9]|1\\d|2[0-8])))`;
const DATE_REGEX = new RegExp(`^${DATE_REGEX_SOURCE}$`);

function timeRegexSource(precision: number | null): string {
  let regex = `([01]\\d|2[0-3]):[0-5]\\d:[0-5]\\d`;
  if (precision) regex = `${regex}\\.\\d{${precision}}`;
  else if (precision == null) regex = `${regex}(\\.\\d+)?`;
  return regex;
}

function timeRegex(precision: number | null): RegExp {
  return new RegExp(`^${timeRegexSource(precision)}$`);
}

function datetimeRegex(args: { precision: number | null; offset: boolean; local: boolean }): RegExp {
  let regex = `${DATE_REGEX_SOURCE}T${timeRegexSource(args.precision)}`;
  const opts: string[] = [];
  opts.push(args.local ? `Z?` : `Z`);
  if (args.offset) opts.push(`([+-]\\d{2}:?\\d{2})`);
  regex = `${regex}(${opts.join("|")})`;
  return new RegExp(`^${regex}$`);
}

export { DATE_REGEX, timeRegex, datetimeRegex };
